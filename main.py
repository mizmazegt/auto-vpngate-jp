import requests
import csv
import base64
import os
import time
import shutil
from io import StringIO
from datetime import datetime
import pytz # Cần thêm thư viện này hoặc dùng datetime cơ bản

# --- CẤU HÌNH ---
VPN_API = "http://www.vpngate.net/api/iphone/"
ISP_API = "http://ip-api.com/json/{}"
SAVE_DIR = "ovpn_files"
README_FILE = "README.md"
CUSTOM_CIPHER = "data-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305:AES-128-CBC"

def get_servers():
    print(f"[*] Đang tải danh sách server...")
    try:
        res = requests.get(VPN_API, timeout=20)
        raw = [line for line in res.text.splitlines() if not line.startswith('*') and line.strip()]
        if "HostName" not in raw[0]:
            header = "HostName,IP,Score,Ping,Speed,CountryLong,CountryShort,NumVpnSessions,Uptime,TotalUsers,TotalTraffic,LogType,Operator,Message,OpenVPN_ConfigData_Base64"
            raw.insert(0, header)
        return list(csv.DictReader(StringIO("\n".join(raw))))
    except Exception as e:
        print(f"[!] Lỗi tải VPN API: {e}")
        return []

def get_isp(ip):
    try:
        res = requests.get(ISP_API.format(ip), timeout=3).json()
        return res.get('isp', 'Unknown').replace(" ", "")
    except:
        return "Unknown"

def clean_ovpn_content(text):
    return "\n".join([line for line in text.splitlines() if line.strip()])

def save_ovpn(server):
    """Lưu file và trả về tên file nếu thành công"""
    try:
        ip = server['IP']
        speed = int(server['Speed']) / 1000000
        isp = get_isp(ip)
        
        filename = f"JP_{isp}_{ip}_{speed:.1f}Mbps.ovpn"
        path = os.path.join(SAVE_DIR, filename)

        raw_b64 = server['OpenVPN_ConfigData_Base64']
        decoded_config = base64.b64decode(raw_b64).decode('utf-8')
        content_cleaned = clean_ovpn_content(decoded_config)
        
        final_data = f"# JP | {isp} | {ip} | {speed:.1f}Mbps\n{CUSTOM_CIPHER}\n{content_cleaned}"
        
        with open(path, 'w', encoding='utf-8') as f:
            f.write(final_data)
        
        # Trả về thông tin để ghi vào Readme
        return {
            "filename": filename,
            "hostname": server.get('HostName', '-'),
            "ip": ip,
            "ping": server.get('Ping', '-'),
            "speed": speed,
            "country": "Japan"
        }
    except:
        return None

def update_readme(success_list):
    """Tạo bảng Markdown trong README.md"""
    
    # Lấy giờ hiện tại (Giờ Việt Nam cho dễ nhìn)
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    md_content = f"""# VPN Gate List - Japan (JP)
**Last Updated:** {now} (UTC)
**Total Servers:** {len(success_list)}

| Hostname | IP Address | Ping | Speed | Country | Download Config |
|:--- |:--- |:--- |:--- |:--- |:--- |
"""
    
    for item in success_list:
        # Tạo link tải file tương đối
        download_link = f"[Download](./{SAVE_DIR}/{item['filename']})"
        row = f"| {item['hostname']} | {item['ip']} | {item['ping']} ms | {item['speed']:.2f} Mbps | {item['country']} | {download_link} |\n"
        md_content += row
    
    md_content += "\n\n*Auto-generated by GitHub Actions*"
    
    with open(README_FILE, 'w', encoding='utf-8') as f:
        f.write(md_content)
    print("[*] Đã cập nhật README.md")

def main():
    if os.path.exists(SAVE_DIR):
        shutil.rmtree(SAVE_DIR)
    os.makedirs(SAVE_DIR)
    
    servers = get_servers()
    jp_list = sorted([s for s in servers if s['CountryShort'] == 'JP'], 
                     key=lambda x: int(x['Speed']), reverse=True)
    
    print(f"[*] Tìm thấy {len(jp_list)} server JP. Bắt đầu xử lý...")

    success_items = []
    
    # Giới hạn 100 server tốt nhất
    for s in jp_list[:100]: 
        result = save_ovpn(s)
        if result:
            success_items.append(result)
        time.sleep(1) # Delay tránh ban IP

    # Sau khi tải xong hết thì cập nhật Readme 1 lần
    update_readme(success_items)
    print(f"[*] Hoàn tất! Đã lưu {len(success_items)} file.")

if __name__ == "__main__":
    main()